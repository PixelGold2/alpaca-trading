export function resolveCountryCentroid(
  sourceCountry: string | undefined,
): { country: string; latitude: number; longitude: number } | null {
  if (!sourceCountry) return null;
  const coords = COUNTRY_NAME_CENTROIDS[sourceCountry.trim()];
  if (!coords) return null;
  return { country: sourceCountry.trim(), latitude: coords[0], longitude: coords[1] };
}
